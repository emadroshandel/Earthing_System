"""
Horizontally layered earth with any number of layers (in practice three).

Contents
--------
* ``LayeredEarth`` — resistivities ρ₁ … ρ_N and thicknesses h₁ … h_{N−1}.
* Surface kernel B(λ) by the reflection recurrence (tutorial Eq. 2.14):

      R_{N−1} = K_{N−1,N},
      R_i     = (K_{i,i+1} + R_{i+1} e^{−2λh_{i+1}}) / (1 + K_{i,i+1} R_{i+1} e^{−2λh_{i+1}}),
      B(λ)    = R_1 e^{−2λh₁} / (1 − R_1 e^{−2λh₁}),

  with K_{i,j} = (ρ_j − ρ_i)/(ρ_j + ρ_i).  The potential of a current I
  entering the surface at a point is V(r) = ρ₁I/(2π) [1/r + 2ψ(r)],
  ψ(r) = ∫₀^∞ B(λ) J₀(λr) dλ  (Stefanescu; Koefoed; Takahashi & Kawase).
  For two layers B = Kx/(1 − Kx), x = e^{−2λh}, and ψ is the familiar image
  series Σ Kⁿ/√(r² + (2nh)²).
* ``apparent`` — Wenner, ideal and finite-MN Schlumberger apparent
  resistivity from ψ, evaluated by Gauss–Legendre quadrature on a fixed set
  of nodes (``HankelPlan``), so that an inversion re-uses the Bessel values.
* ``image_series`` — the exact image expansion of the Green's function for a
  source in any layer and a field point in any layer, generated by tracing
  the reflected and transmitted "waves" between the planes (tutorial §8.6).
  A wave in layer L meeting a plane is reflected with R = (ρ_M − ρ_L)/(ρ_M + ρ_L)
  and transmitted with 1 + R; the air surface reflects with R = +1.  Every
  wave is a point source 1/√(r² + (z − ζ)²) whose position ζ = s·z' + Σ 2n_k d_k
  does not depend on the source depth except through the sign s, so the
  coefficients are computed once per soil model.  This is what the
  boundary-element solver uses.
* ``invert_layers`` — least-squares fit of a two- or three-layer earth by a
  Levenberg–Marquardt search in log parameters from many starting points,
  with the linearised covariance, the parameter correlations, the
  equivalence (which combination of a middle layer's ρ and h the data
  actually fix) and the F-test of three layers against two.
* ``disc_factor`` / ``equivalent_uniform`` / ``equivalent_two_layer`` — the
  grid-size rule of tutorial §6.4 for any number of layers.

numpy only: the module also runs in the browser build.
"""

from __future__ import annotations

import math
from typing import Sequence

import numpy as np


# ---------------------------------------------------------------------------
# Bessel functions J0 and J1 (numpy has none).  Rational and asymptotic
# approximations of Hart et al. as given in Numerical Recipes, 2nd ed., §6.5;
# absolute error below 1e-8, which is far below the quadrature error used.
# ---------------------------------------------------------------------------

_TWO_PI = 2.0 * np.pi


def _reduce(u):
    """Reduce angles to (-2π, 2π) before cos/sin.  fmod is exact in floating
    point, so nothing is lost; and on some machines numpy's vectorised cos
    and sin take a large-argument path that raises a hardware floating-point
    exception (SIGFPE, killing the process) on arguments of 10^5 and more,
    which the Bessel tails reach."""
    return np.fmod(u, _TWO_PI)


def j0(x):
    x = np.asarray(x, float)
    ax = np.abs(x)
    out = np.empty_like(ax)
    s = ax < 8.0
    if s.any():
        y = x[s] ** 2
        a1 = 57568490574.0 + y * (-13362590354.0 + y * (651619640.7 + y * (
            -11214424.18 + y * (77392.33017 + y * (-184.9052456)))))
        a2 = 57568490411.0 + y * (1029532985.0 + y * (9494680.718 + y * (
            59272.64853 + y * (267.8532712 + y * 1.0))))
        out[s] = a1 / a2
    b = ~s
    if b.any():
        z = 8.0 / ax[b]
        y = z * z
        xx = ax[b] - 0.785398164
        a1 = 1.0 + y * (-0.1098628627e-2 + y * (0.2734510407e-4 + y * (
            -0.2073370639e-5 + y * 0.2093887211e-6)))
        a2 = -0.1562499995e-1 + y * (0.1430488765e-3 + y * (
            -0.6911147651e-5 + y * (0.7621095161e-6 - y * 0.934935152e-7)))
        xx = _reduce(xx)
        out[b] = np.sqrt(0.636619772 / ax[b]) * (np.cos(xx) * a1 - z * np.sin(xx) * a2)
    return out


def j1(x):
    x = np.asarray(x, float)
    ax = np.abs(x)
    out = np.empty_like(ax)
    s = ax < 8.0
    if s.any():
        xs = x[s]
        y = xs * xs
        a1 = xs * (72362614232.0 + y * (-7895059235.0 + y * (242396853.1 + y * (
            -2972611.439 + y * (15704.48260 + y * (-30.16036606))))))
        a2 = 144725228442.0 + y * (2300535178.0 + y * (18583304.74 + y * (
            99447.43394 + y * (376.9991397 + y * 1.0))))
        out[s] = a1 / a2
    b = ~s
    if b.any():
        z = 8.0 / ax[b]
        y = z * z
        xx = ax[b] - 2.356194491
        a1 = 1.0 + y * (0.183105e-2 + y * (-0.3516396496e-4 + y * (
            0.2457520174e-5 + y * (-0.240337019e-6))))
        a2 = 0.04687499995 + y * (-0.2002690873e-3 + y * (
            0.8449199096e-5 + y * (-0.88228987e-6 + y * 0.105787412e-6)))
        xx = _reduce(xx)
        out[b] = np.sqrt(0.636619772 / ax[b]) * (np.cos(xx) * a1 - z * np.sin(xx) * a2) \
            * np.sign(x[b])
    return out


_GL10 = np.polynomial.legendre.leggauss(10)


# ---------------------------------------------------------------------------
# The layered earth
# ---------------------------------------------------------------------------

class LayeredEarth:
    """ρ₁ … ρ_N (Ω·m) and thicknesses h₁ … h_{N−1} (m); the last layer is
    infinitely deep.  Depth z is positive downwards."""

    def __init__(self, rho: Sequence[float], h: Sequence[float] = ()):
        rho = [float(r) for r in rho]
        h = [float(t) for t in h]
        if len(rho) < 1 or len(h) != len(rho) - 1:
            raise ValueError("A model with N layers needs N resistivities and "
                             "N − 1 thicknesses.")
        if min(rho) <= 0 or (h and min(h) <= 0):
            raise ValueError("Every resistivity and thickness must be greater "
                             "than zero.")
        self.rho = rho
        self.h = h
        self.N = len(rho)
        self.depths = list(np.cumsum(h)) if h else []      # interface depths
        self.K = [(rho[i + 1] - rho[i]) / (rho[i + 1] + rho[i])
                  for i in range(self.N - 1)]

    # -- descriptive ----------------------------------------------------------
    def layer_of(self, z: float) -> int:
        """1-based layer index of depth z."""
        return 1 + sum(1 for d in self.depths if z > d)

    def describe(self) -> str:
        parts = []
        for i, r in enumerate(self.rho):
            if i < len(self.h):
                parts.append(f"ρ{i + 1} = {r:g} Ω·m to {self.depths[i]:g} m")
            else:
                parts.append(f"ρ{i + 1} = {r:g} Ω·m below")
        return f"{self.N}-layer soil: " + ", ".join(parts)

    # -- surface kernel -------------------------------------------------------
    def kernel(self, lam):
        """B(λ) such that T₁/ρ₁ = 1 + 2B (surface source, surface field)."""
        lam = np.asarray(lam, float)
        if self.N == 1:
            return np.zeros_like(lam)
        R = np.full_like(lam, self.K[-1])
        for i in range(self.N - 3, -1, -1):
            e = np.exp(-2.0 * lam * self.h[i + 1])
            K = self.K[i]
            R = (K + R * e) / (1.0 + K * R * e)
        x = R * np.exp(-2.0 * lam * self.h[0])
        return x / (1.0 - x)

    def kernel_top(self, lam):
        """The two-layer kernel of the top interface alone, K₁₂x/(1 − K₁₂x),
        x = e^{−2λh₁}; B − kernel_top decays like e^{−2λ(h₁ + h₂)}."""
        lam = np.asarray(lam, float)
        if self.N == 1:
            return np.zeros_like(lam)
        x = self.K[0] * np.exp(-2.0 * lam * self.h[0])
        return x / (1.0 - x)

    def psi_top(self, r, derivative: bool = False):
        """Σ K₁₂ⁿ/√(r² + (2nh₁)²) (or its r-derivative): the Hankel transform
        of kernel_top, summed as images to |K₁₂|ⁿ < 10⁻¹³."""
        r = np.asarray(r, float)
        if self.N == 1:
            return np.zeros_like(r)
        K, h = self.K[0], self.h[0]
        aK = abs(K)
        n_max = 1 if aK < 1e-15 else int(min(40000, math.ceil(math.log(1e-13) / math.log(aK))))
        n = np.arange(1, max(n_max, 1) + 1, dtype=float)
        Kn = np.sign(K) ** n * np.exp(n * math.log(max(aK, 1e-300)))
        D2 = (2.0 * n * h) ** 2
        out = np.empty_like(r)
        for i, rr in enumerate(r):
            R2 = rr * rr + D2
            out[i] = (-(Kn * rr / R2 ** 1.5).sum() if derivative
                      else (Kn / np.sqrt(R2)).sum())
        return out

    def kernel_integral(self) -> float:
        """∫₀^∞ B(λ) dλ = Σ c_k/D_k over the surface images (used for the
        closed-form remainder of image sums)."""
        if self.N == 1:
            return 0.0
        dmax = self.depths[-1]
        dmin = min(self.h)
        # B decays like e^{-2λh₁}; Gauss–Legendre on geometric panels
        edges = np.concatenate([[0.0], np.geomspace(1e-8 / dmax, 40.0 / dmin, 400)])
        t, w = _GL10
        a, b = edges[:-1], edges[1:]
        lam = (0.5 * (a + b))[:, None] + (0.5 * (b - a))[:, None] * t[None, :]
        wt = (0.5 * (b - a))[:, None] * w[None, :]
        return float(np.sum(self.kernel(lam.ravel()) * wt.ravel()))


# ---------------------------------------------------------------------------
# Hankel transform ψ(r) = ∫ B(λ) J0(λr) dλ on a fixed node set
# ---------------------------------------------------------------------------

class HankelPlan:
    """Gauss–Legendre nodes for ψ(r) and ψ'(r) at a fixed set of distances.

    The nodes depend only on the distances and on the thinnest top layer the
    model is allowed to have (``h_min``), so the Bessel values are computed
    once and every forward evaluation is one kernel evaluation and one
    matrix–vector product.  Panels: geometric from λ ≈ 0 up to 0.5/r_max (the
    region where a resistive or conductive basement acts), then half-periods
    π/r_max of the most oscillatory Bessel function, up to the point where
    the kernel, which decays like e^{−2λh₁}, is below 10⁻¹².
    """

    def __init__(self, r: Sequence[float], h_min: float, depth_max: float,
                 derivative: bool = False):
        r = np.asarray(sorted(set(float(x) for x in r)), float)
        if r.size == 0 or r.min() <= 0:
            raise ValueError("Distances must be greater than zero.")
        self.r = r
        self.h_min = float(h_min)          # least decay length / 2 of the kernel
        rmax = float(r.max())
        lam_max = 10.0 / self.h_min          # e^{−2λd} < 2·10⁻⁹ beyond
        lam_lo = 1e-6 / (rmax + depth_max)
        lam_mid = min(0.5 / rmax, lam_max)
        geo = np.geomspace(lam_lo, lam_mid, 48)
        step = min(2.0 * math.pi / rmax, 0.6 / self.h_min)
        n_lin = max(1, int(math.ceil((lam_max - lam_mid) / step)))
        lin = np.linspace(lam_mid, lam_max, n_lin + 1)
        edges = np.concatenate([[0.0], geo, lin[1:]])
        t, w = _GL10
        a, b = edges[:-1], edges[1:]
        mid, half = 0.5 * (a + b), 0.5 * (b - a)
        self.lam = (mid[:, None] + half[:, None] * t[None, :]).ravel()
        wts = (half[:, None] * w[None, :]).ravel()
        X = self.r[:, None] * self.lam[None, :]
        self.W0 = j0(X) * wts[None, :]
        self.W1 = (j1(X) * self.lam[None, :]) * wts[None, :] if derivative else None
        self.index = {float(x): i for i, x in enumerate(self.r)}

    def psi(self, earth: LayeredEarth):
        """ψ(r) = ψ_top(r) + ∫ (B − B_top) J0(λr) dλ: the top interface is
        summed exactly as images, the quadrature carries only the part that
        the deeper interfaces add."""
        if earth.N <= 2:
            return earth.psi_top(self.r)
        dB = earth.kernel(self.lam) - earth.kernel_top(self.lam)
        return earth.psi_top(self.r) + self.W0 @ dB

    def dpsi(self, earth: LayeredEarth):
        """ψ'(r) = ψ_top'(r) − ∫ λ (B − B_top) J1(λr) dλ."""
        if earth.N <= 2:
            return earth.psi_top(self.r, derivative=True)
        dB = earth.kernel(self.lam) - earth.kernel_top(self.lam)
        return earth.psi_top(self.r, derivative=True) - (self.W1 @ dB)


# ---------------------------------------------------------------------------
# Apparent resistivity of the arrays
# ---------------------------------------------------------------------------

def _array_distances(array: str, xs, mn=None):
    if array == "wenner":
        return [a for x in xs for a in (x, 2 * x)]
    out = []
    for i, s in enumerate(xs):
        d = (mn[i] if mn is not None else None) or 0.0
        if 0.0 < d < 2.0 * s:
            out += [s - d / 2.0, s + d / 2.0]
        else:
            out.append(s)
    return out


class ArrayModel:
    """Apparent-resistivity forward model for a fixed set of readings."""

    def __init__(self, array: str, xs, mn=None, h_min: float | None = None,
                 depth_max: float | None = None):
        array = array.lower()
        if array not in ("wenner", "schlumberger"):
            raise ValueError("Array must be 'wenner' or 'schlumberger'.")
        self.array = array
        self.xs = [float(x) for x in xs]
        self.mn = [float(m) if m else 0.0 for m in mn] if mn is not None else None
        self.hmin = h_min if h_min else 0.05 * min(self.xs)
        self.dmax = depth_max if depth_max else 10.0 * max(self.xs)
        self.ideal = array == "schlumberger" and (
            self.mn is None or any(not (0 < m < 2 * s) for m, s in zip(self.mn, self.xs)))
        self.dist = _array_distances(array, self.xs, self.mn)
        self._plans = {}
        self.plan = self._plan_for(self.hmin)

    def _plan_for(self, d2: float) -> HankelPlan:
        """Quadrature plan for a model whose second interface is at d2 or
        deeper: plans are cached in octaves of d2 above the floor, so a
        deep interface is integrated on few nodes and a shallow one on many."""
        k = int(max(0, min(12, math.floor(math.log2(max(d2, self.hmin) / self.hmin)))))
        if k not in self._plans:
            self._plans[k] = HankelPlan(self.dist, self.hmin * 2 ** k, self.dmax,
                                        derivative=self.ideal)
        return self._plans[k]

    def __call__(self, earth: LayeredEarth):
        rho1 = earth.rho[0]
        if earth.N == 1:
            return np.full(len(self.xs), rho1)
        P = self._plan_for(earth.depths[1]) if earth.N >= 3 else self.plan
        psi = P.psi(earth)
        out = np.empty(len(self.xs))
        dps = None
        for i, x in enumerate(self.xs):
            if self.array == "wenner":
                a = x
                out[i] = rho1 * (1.0 + 4.0 * a * (psi[P.index[a]] - psi[P.index[2 * a]]))
            else:
                d = self.mn[i] if self.mn is not None else 0.0
                if 0.0 < d < 2.0 * x:
                    xm, xp = x - d / 2.0, x + d / 2.0
                    g = (x * x - d * d / 4.0) / d
                    out[i] = rho1 * (1.0 + 2.0 * g * (psi[P.index[xm]] - psi[P.index[xp]]))
                else:
                    if dps is None:
                        dps = P.dpsi(earth)
                    out[i] = rho1 * (1.0 + 2.0 * x * x * (-dps[P.index[x]]))
        return out


def apparent(earth: LayeredEarth, array: str, xs, mn=None,
             chunk: int = 6) -> np.ndarray:
    """Apparent resistivity of ``earth`` for each spacing (a or AB/2).

    Evaluated a few spacings at a time so that the Bessel table stays small
    (a 120-point plotting curve would otherwise need hundreds of MB)."""
    xs = [float(x) for x in xs]
    if earth.N == 1:
        return np.full(len(xs), earth.rho[0])
    d2 = earth.depths[1] if earth.N >= 3 else earth.h[0]
    out = []
    for i in range(0, len(xs), chunk):
        part = xs[i:i + chunk]
        mp = mn[i:i + chunk] if mn is not None else None
        m = ArrayModel(array, part, mp, h_min=d2,
                       depth_max=earth.depths[-1] + max(part))
        out.append(m(earth))
    return np.concatenate(out)


# ---------------------------------------------------------------------------
# Image expansion of the Green's function (for the boundary-element solver)
# ---------------------------------------------------------------------------

def image_series(earth: LayeredEarth, src_layer: int, tol: float = 1e-10,
                 max_generations: int = 200000, prune_beyond: float | None = None,
                 with_direction: bool = False):
    """All images of a unit point source in ``src_layer`` (1-based).

    Returns {field_layer: (s, shift, amp)} with numpy arrays (and a fourth,
    the direction 0 = up-going, 1 = down-going, 2 = the primary, when
    ``with_direction``): the field in that layer is
    ρ_src/(4π) Σ amp / √(r² + (z − s·z' − shift)²).

    Waves are traced plane to plane, vectorised over all the waves of one
    generation.  A wave is (layer, direction, s, shift, amplitude), its
    source sitting at ζ = s·z' + shift; reflection at the plane at depth dₖ
    maps ζ → 2dₖ − ζ, i.e. s → −s, shift → 2dₖ − shift, and multiplies the
    amplitude by R = (ρ_M − ρ_L)/(ρ_M + ρ_L); transmission keeps ζ and
    multiplies by 1 + R; the air surface reflects with R = +1.  Waves at the
    same place travelling the same way are merged, and a wave whose
    amplitude falls below ``tol`` is dropped.

    The distance from a wave's source to the plane it is heading for never
    decreases along its descendants (each bounce adds a layer thickness), so
    with ``prune_beyond`` = D a wave is dropped once |shift − plane| > D:
    every image it would still produce lies further than D − 2·max(z, z')
    from any field point.  The boundary-element solver takes those from the
    spectral solution instead (``LayeredGreen``).
    """
    N = earth.N
    i0 = src_layer - 1
    rho = np.asarray(earth.rho, float)
    plane = np.array([0.0] + list(earth.depths), float)   # plane k depth
    R_up = np.zeros(N)
    R_dn = np.zeros(N)
    R_up[0] = 1.0
    for L in range(1, N):
        R_up[L] = (rho[L - 1] - rho[L]) / (rho[L - 1] + rho[L])
    for L in range(N - 1):
        R_dn[L] = (rho[L + 1] - rho[L]) / (rho[L + 1] + rho[L])
    Q = 1e7                                   # position quantum 0.1 µm

    def code(Lr, dr, sr, shr):
        return ((np.round(shr * Q).astype(np.int64) * 4 + Lr) * 4 + dr) * 2 + (sr > 0)

    def merge(Lr, dr, sr, shr, ar):
        if ar.size == 0:
            return Lr, dr, sr, shr, ar
        u, idx, inv = np.unique(code(Lr, dr, sr, shr), return_index=True,
                                return_inverse=True)
        return Lr[idx], dr[idx], sr[idx], shr[idx], \
            np.bincount(inv, weights=ar, minlength=len(u))

    coll = [(np.array([i0]), np.array([2]), np.array([1]), np.array([0.0]),
             np.array([1.0]))]
    L = np.array([i0, i0]); d = np.array([0, 1]); sg = np.array([1, 1])
    sh = np.zeros(2); a = np.ones(2)
    gen = 0
    while a.size and gen < max_generations:
        gen += 1
        parts = []
        up = d == 0
        if up.any():
            Lu, su, hu, au = L[up], sg[up], sh[up], a[up]
            Ru = R_up[Lu]
            parts.append((Lu, np.ones_like(Lu), -su, 2.0 * plane[Lu] - hu, au * Ru))
            t = Lu > 0
            if t.any():
                parts.append((Lu[t] - 1, np.zeros(t.sum(), int), su[t], hu[t],
                              au[t] * (1.0 + Ru[t])))
        dn = (~up) & (L < N - 1)
        if dn.any():
            Ld, sd, hd, ad = L[dn], sg[dn], sh[dn], a[dn]
            Rd = R_dn[Ld]
            parts.append((Ld, np.zeros_like(Ld), -sd, 2.0 * plane[Ld + 1] - hd, ad * Rd))
            parts.append((Ld + 1, np.ones_like(Ld), sd, hd, ad * (1.0 + Rd)))
        if not parts:
            break
        L, d, sg, sh, a = (np.concatenate([p[i] for p in parts]) for i in range(5))
        L, d, sg, sh, a = merge(L, d, sg, sh, a)
        coll.append((L, d, sg, sh, a))
        keep = np.abs(a) > tol
        keep &= ~((d == 1) & (L == N - 1))            # nothing left to meet
        if prune_beyond is not None:
            target = np.where(d == 0, plane[L], plane[np.minimum(L + 1, N - 1)])
            keep &= np.abs(sh - target) <= prune_beyond
        L, d, sg, sh, a = L[keep], d[keep], sg[keep], sh[keep], a[keep]
        if len(coll) > 48:
            parts2 = [np.concatenate([c[i] for c in coll]) for i in range(5)]
            coll = [merge(*parts2)]
    CL, CD, CS, CH, CA = (np.concatenate([c[i] for c in coll]) for i in range(5))
    CL, CD, CS, CH, CA = merge(CL, CD, CS, CH, CA)
    out = {}
    for Lf in range(N):
        m = (CL == Lf) & (CA != 0.0)
        if with_direction:
            out[Lf + 1] = (CS[m].astype(int), CH[m], CA[m], CD[m].astype(int))
        else:
            # one image per position whatever the direction it travels
            s_, h_, a_ = CS[m].astype(int), CH[m], CA[m]
            if a_.size:
                u, idx, inv = np.unique(np.round(h_ * Q).astype(np.int64) * 2 + (s_ > 0),
                                        return_index=True, return_inverse=True)
                a_ = np.bincount(inv, weights=a_, minlength=len(u))
                s_, h_ = s_[idx], h_[idx]
            out[Lf + 1] = (s_, h_, a_)
    return out


def surface_images(earth: LayeredEarth, tol: float = 1e-12):
    """(depth D_k, coefficient c_k) with ψ(r) = Σ c_k/√(r² + D_k²): the image
    series of the surface kernel, from the general expansion with source and
    field on the surface (the primary and its air image are removed)."""
    if earth.N == 1:
        return np.zeros(0), np.zeros(0)
    s, sh, a = image_series(earth, 1, tol=tol)[1]
    # at z = z' = 0 the sign is irrelevant; D = |shift|, merge
    D = np.round(np.abs(sh), 9)
    u, inv = np.unique(D, return_inverse=True)
    c = np.zeros(len(u))
    np.add.at(c, inv, a)
    keep = u > 0
    # At z = z' = 0 the four images (±z', ±shift) of each order coincide, and
    # V = ρ₁I/(4π)[2/r + Σ amp/R] = ρ₁I/(2π)[1/r + 2ψ]  gives  c = amp/4.
    return u[keep], 0.25 * c[keep]


# ---------------------------------------------------------------------------
# Equivalent resistivity for a grid (tutorial §6.4, any number of layers)
# ---------------------------------------------------------------------------

def disc_factor(earth: LayeredEarth, r: float) -> float:
    """F = R_disc(layered)/R_disc(uniform ρ₁) for a surface disc of radius r,
    the multi-layer form of tutorial Eq. 6.5.  Over the surface images
    (c_k, D_k) of the kernel it reads

        F = 1 + (4/πr) Σ_k c_k [ r·atan(r/q_k) − (q_k/2)·ln(1 + r²/q_k²) ],
        q_k = D_k/2,

    and since  ∫₀^∞ e^{−λq}(1 − cos λr)/λ² dλ = r·atan(r/q) − (q/2)ln(1 + r²/q²),
    the image sum is one smooth integral of the kernel itself:

        F = 1 + (4/πr) ∫₀^∞ B(μ) (1 − cos 2μr)/(2μ²) dμ,

    which needs no image series however slowly that would converge.
    """
    if earth.N == 1:
        return 1.0
    r = float(r)
    h1 = earth.h[0]
    dmax = earth.depths[-1]
    mu_max = 40.0 / h1
    mid = min(0.25 / r, mu_max)
    geo = np.geomspace(1e-9 / (dmax + r), mid, 120)
    step = min(math.pi / (4.0 * r), 0.25 / h1)
    lin = np.linspace(mid, mu_max, max(2, int(math.ceil((mu_max - mid) / step)) + 1))
    edges = np.concatenate([[0.0], geo, lin[1:]])
    t, w = _GL10
    a, b = edges[:-1], edges[1:]
    mu = ((0.5 * (a + b))[:, None] + (0.5 * (b - a))[:, None] * t[None, :]).ravel()
    wt = ((0.5 * (b - a))[:, None] * w[None, :]).ravel()
    x = 2.0 * mu * r
    # (1 − cos x)/(2μ²) = 2r² (1 − cos x)/x², evaluated stably for small x
    f = np.where(x < 1e-3, 1.0 - x * x / 12.0, 2.0 * (1.0 - np.cos(_reduce(x))) / np.maximum(x * x, 1e-300))
    S = float(np.sum(earth.kernel(mu) * f * wt)) * r * r
    # beyond μ_max: B ≈ R₁e^{−2μh₁}, (1 − cos)/(2μ²) ≤ 1/μ² — below 10⁻¹⁷ relative
    return 1.0 + 4.0 / (math.pi * r) * S


def equivalent_uniform(earth: LayeredEarth, area: float,
                       total_length: float | None = None) -> dict:
    """Grid-size rule for a layered earth: the uniform resistivity that gives
    a disc of the grid's area the resistance it has on the layered soil,
    with the conductor term ρ₁/L_T kept in the top layer (tutorial §6.4)."""
    if area is None or area <= 0:
        raise ValueError("The grid-size rule needs the grid area (m²).")
    r = math.sqrt(area / math.pi)
    F = disc_factor(earth, r)
    rho1 = earth.rho[0]
    if total_length and total_length > 0:
        LT = float(total_length)
        ratio = (F / (4 * r) + 1 / LT) / (1 / (4 * r) + 1 / LT)
    else:
        LT, ratio = None, F
    return dict(rho_equivalent=rho1 * ratio, F=F, r_equiv=r, ratio=ratio,
                area=area, total_length=LT, method_used="grid", layers=earth.N)


def equivalent_two_layer(earth: LayeredEarth, area: float,
                         grid_depth: float = 0.5) -> dict:
    """Collapse a three-layer model to two layers for one particular grid.

    The top layer — the soil around the conductors — is kept as it is
    (ρ₁, h₁), and the two lower layers are replaced by a single half-space
    ρ_b chosen so that a disc of the grid's area has the same resistance on
    both models (equal disc factor F at r = √(A/π)).  The far field of the
    grid, which sets R_g, is then the same; the near field around the
    conductors, which sets the mesh voltage, lies in ρ₁ in both.  If the
    grid is buried below h₁, the top two layers are kept together and only
    the basement is replaced.
    """
    if earth.N < 3:
        if earth.N == 2:
            return dict(rho1=earth.rho[0], rho2=earth.rho[1], h=earth.h[0],
                        F=disc_factor(earth, math.sqrt(area / math.pi)),
                        exact=True, note="The model already has two layers.")
        return dict(rho1=earth.rho[0], rho2=earth.rho[0], h=1.0, F=1.0,
                    exact=True, note="Uniform soil.")
    r = math.sqrt(area / math.pi)
    F3 = disc_factor(earth, r)
    rho1, h = earth.rho[0], earth.h[0]
    note = ""
    if grid_depth >= h:
        # conductors in layer 2: keep a top layer with the thickness-weighted
        # resistivity of layers 1–2 down to the second interface
        h = earth.depths[1]
        rho1 = h / (earth.h[0] / earth.rho[0] + earth.h[1] / earth.rho[1])
        note = ("The grid is buried in the second layer, so layers 1 and 2 "
                "are merged into one top layer of the same conductance "
                "h/ρ before the basement is matched. ")

    def F2(rb):
        return disc_factor(LayeredEarth([rho1, rb], [h]), r)

    target = F3 * earth.rho[0] / rho1        # same disc resistance
    lo, hi = math.log(1e-3 * rho1), math.log(1e5 * rho1)
    flo, fhi = F2(math.exp(lo)) - target, F2(math.exp(hi)) - target
    if flo > 0 or fhi < 0:
        rb = math.exp(lo) if flo > 0 else math.exp(hi)
        note += "The match is at the edge of the search range. "
    else:
        for _ in range(80):
            mid = 0.5 * (lo + hi)
            if F2(math.exp(mid)) - target > 0:
                hi = mid
            else:
                lo = mid
        rb = math.exp(0.5 * (lo + hi))
    return dict(rho1=rho1, rho2=rb, h=h, F=F3, r_equiv=r, exact=False,
                note=(note + f"Top layer kept (ρ₁ = {rho1:.4g} Ω·m, "
                      f"h = {h:.3g} m); the layers below replaced by "
                      f"ρ₂ = {rb:.4g} Ω·m, which gives a disc of the grid's "
                      f"area (r = {r:.1f} m) the same resistance, F = {F3:.4f}."))


