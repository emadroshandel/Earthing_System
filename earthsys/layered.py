def _model_from(p, n_layers):
    v = np.exp(p)
    return LayeredEarth(v[:n_layers], v[n_layers:])


def _lm(fun, p0, lo, hi, max_iter=80, tol=1e-10):
    """Levenberg–Marquardt on residual vector fun(p) with box bounds."""
    p = np.clip(np.asarray(p0, float), lo, hi)
    r = fun(p)
    f = float(r @ r)
    mu = 1e-2
    n = len(p)
    for _ in range(max_iter):
        J = np.empty((len(r), n))
        for j in range(n):
            dp = np.zeros(n)
            dp[j] = 1e-5
            pj = np.clip(p + dp, lo, hi)
            step = pj[j] - p[j]
            if abs(step) < 1e-12:
                pj = np.clip(p - dp, lo, hi)
                step = pj[j] - p[j]
            J[:, j] = (fun(pj) - r) / step
        g = J.T @ r
        A = J.T @ J
        improved = False
        for _k in range(12):
            try:
                delta = np.linalg.solve(A + mu * np.diag(np.diag(A) + 1e-12), -g)
            except np.linalg.LinAlgError:
                mu *= 10
                continue
            pn = np.clip(p + delta, lo, hi)
            rn = fun(pn)
            fn = float(rn @ rn)
            if np.isfinite(fn) and fn < f:
                rel = (f - fn) / max(f, 1e-30)
                p, r, f = pn, rn, fn
                mu = max(mu / 4, 1e-9)
                improved = True
                break
            mu *= 6
        if not improved or rel < tol:
            break
    return p, f


def f_test_nested(ss_a, ss_b, n, p_a, p_b):
    """F test of a model with p_b parameters against a nested one with p_a
    (p_b - p_a even).  Returns (F, p).  For an even numerator d1 = 2m the
    upper tail has the closed form
    P(F > f) = x^{d2/2} Σ_{j<m} [Γ(d2/2 + j)/(Γ(d2/2) j!)] (1 − x)^j,
    x = d2/(d2 + d1 f)."""
    d1, d2 = p_b - p_a, n - p_b
    if d2 <= 0 or ss_b <= 0 or d1 <= 0 or d1 % 2:
        return None, None
    F = ((ss_a - ss_b) / d1) / (ss_b / d2)
    if F <= 0:
        return F, 1.0
    x = d2 / (d2 + d1 * F)
    term, tot = 1.0, 1.0
    for j in range(1, d1 // 2):
        term *= (d2 / 2.0 + j - 1) / j * (1.0 - x)
        tot += term
    return F, min(1.0, x ** (d2 / 2.0) * tot)


def _f_test_p(ss2, ss3, n):
    """p-value of the F test of a 3-layer (5 parameters) against a 2-layer
    (3 parameters) fit.  With 2 numerator degrees of freedom the F
    distribution has the closed form P(F > f) = (d₂/(d₂ + 2f))^{d₂/2}."""
    d2 = n - 5
    if d2 <= 0 or ss3 <= 0:
        return None, None
    F = ((ss2 - ss3) / 2.0) / (ss3 / d2)
    if F <= 0:
        return F, 1.0
    return F, (d2 / (d2 + 2.0 * F)) ** (d2 / 2.0)


def _starts(xs, ys, n_layers):
    order = np.argsort(xs)
    x = np.asarray(xs, float)[order]
    y = np.asarray(ys, float)[order]
    y0, yN = y[0], y[-1]
    a_min, a_max = x[0], x[-1]
    S = []
    if n_layers == 2:
        for r1 in (y0, y.max(), y.min(), math.sqrt(y.max() * y.min())):
            for r2 in (yN, y.max(), y.min()):
                for h in (0.3 * a_max, math.sqrt(a_min * a_max), a_min):
                    S.append([r1, r2, h])
        return S
    i_ext_min, i_ext_max = int(np.argmin(y)), int(np.argmax(y))
    mids = []
    for i in {i_ext_min, i_ext_max, len(y) // 2}:
        mids.append((y[i], x[i]))
    for r2, a_e in mids:
        for f2 in (0.6, 1.0, 1.6) if r2 not in (y0, yN) else (0.4, 2.5):
            for h1 in (0.4 * a_min, a_min, 0.3 * a_e, 0.6 * a_e):
                for t in (0.5 * a_e, 1.5 * a_e, 4.0 * a_e):
                    for r1, r3 in ((y0, yN), (1.2 * y0, 1.3 * yN if yN > y.min() else 0.7 * yN)):
                        if h1 > 0 and t > 0:
                            S.append([r1, r2 * f2, r3, h1, t])
    # every third of the grid of starts: in a test on 30 random three-layer
    # earths (contrasts to 25:1 per interface, noise-free readings) this
    # found the global minimum every time, as the full grid did, in 40 % of
    # the time
    return S[::3]


def invert_layers(spacings, rho_app, n_layers: int = 3, array: str = "wenner",
                  mn=None, starts=None, max_starts: int | None = None) -> dict:
    """Least-squares fit of an n-layer earth (n = 2 or 3) to apparent
    resistivity, minimising Σ((ρ_model − ρ_measured)/ρ_measured)²."""
    if n_layers not in (2, 3, 4):
        raise ValueError("Two, three or four layers are supported.")
    xs = [float(s) for s in spacings]
    ys = np.array([float(r) for r in rho_app])
    npar = 2 * n_layers - 1
    if len(xs) < npar + 1:
        raise ValueError(f"A {n_layers}-layer fit has {npar} parameters and "
                         f"needs at least {npar + 1} readings; "
                         f"{len(xs)} were given.")
    if min(xs) <= 0 or ys.min() <= 0:
        raise ValueError("Spacings and readings must be greater than zero.")
    mns = None
    if array == "schlumberger" and mn is not None:
        mns = [float(m) if m else 0.0 for m in mn]
    a_min, a_max = min(xs), max(xs)
    # thickness floors: a layer much thinner than the shortest spacing is not
    # seen by the data; they also bound the quadrature (h₁ + h₂ ≥ 0.15 a_min)
    h_floor = [0.05 * a_min, 0.10 * a_min, 0.10 * a_min][:n_layers - 1]
    fm = ArrayModel(array, xs, mns, h_min=sum(h_floor[:2]) if n_layers >= 3 else h_floor[0],
                    depth_max=20 * a_max)
    lo = np.array([math.log(0.02 * ys.min())] * n_layers
                  + [math.log(f) for f in h_floor])
    hi = np.array([math.log(50.0 * ys.max())] * n_layers
                  + [math.log(5.0 * a_max)] * (n_layers - 1))

    def res(p):
        m = fm(_model_from(p, n_layers))
        return (m - ys) / ys

    S = starts if starts is not None else _starts(xs, ys, n_layers)
    if max_starts:
        S = S[:max_starts]
    # stage 1: a few Levenberg–Marquardt steps from every start;
    # stage 2: the six best (distinct) are taken to convergence.
    trial = []
    for s0 in S:
        p0 = np.clip(np.log(np.maximum(np.asarray(s0, float), 1e-9)), lo, hi)
        p, f = _lm(res, p0, lo, hi, max_iter=6)
        if np.isfinite(f):
            trial.append((f, p))
    trial.sort(key=lambda t: t[0])
    picked = []
    for f, p in trial:
        if all(np.max(np.abs(p - q)) > 0.05 for _, q in picked):
            picked.append((f, p))
        if len(picked) == 6:
            break
    best_p, best_f = None, math.inf
    for f0, p0 in picked:
        p, f = _lm(res, p0, lo, hi, max_iter=150, tol=1e-13)
        if f < best_f:
            best_p, best_f = p, f
    earth = _model_from(best_p, n_layers)
    fitted = fm(earth)
    resid = (fitted - ys) / ys * 100.0
    n = len(xs)
    rms = math.sqrt(best_f / n) * 100.0
    unc = _uncertainty(res, best_p, best_f, n, n_layers, lo, hi)
    out = dict(n_layers=n_layers, rho=earth.rho, h=earth.h,
               depths=earth.depths, K=earth.K, rms_pct=rms, ss=best_f,
               fitted=fitted.tolist(), residual_pct=resid.tolist(),
               spacings=xs, measured=ys.tolist(), array=array,
               uncertainty=unc,
               at_bound=[bool(abs(best_p[i] - lo[i]) < 1e-6 or
                              abs(best_p[i] - hi[i]) < 1e-6)
                         for i in range(len(best_p))])
    cx = np.geomspace(a_min * 0.7, a_max * 1.4, 120)
    cmn = None
    if mns:
        ratio = [m / x if x else 0.0 for x, m in zip(xs, mns)]
        cmn = [ratio[int(np.argmin(np.abs(np.log(np.asarray(xs) / c))))] * c
               for c in cx]
    out["curve_x"] = cx.tolist()
    out["curve_y"] = apparent(earth, array, cx, cmn).tolist()
    return out


def _equivalence(C, sd, corr, v, i_r, i_h):
    """Which combination h·ρ^β of one middle layer the readings fix
    (tutorial Eq. 2.16).  i_r, i_h: indices of its log ρ and log h."""
    SUB = '₀₁₂₃₄₅₆₇₈₉'
    S, S1, S3 = SUB[i_r + 1], SUB[i_r], SUB[i_r + 2]
    c = float(corr[i_r, i_h])
    Crr, Chh, Crh = C[i_r, i_r], C[i_h, i_h], C[i_r, i_h]
    # the combination h{S}·ρ{S}^β the data fix best: log h{S} + β log ρ{S} has
    # least variance for β = −C_rh/C_rr, and that variance is C_hh(1 − c²)
    beta = -Crh / Crr if Crr > 0 else 0.0
    sd_c = math.sqrt(max(Chh - Crh * Crh / Crr, 0.0)) if Crr > 0 else math.sqrt(Chh)
    kind = "conductive" if v[i_r] < min(v[i_r - 1], v[i_r + 1]) else (
        "resistive" if v[i_r] > max(v[i_r - 1], v[i_r + 1]) else "intermediate")
    lv = math.log(v[i_h]) + beta * math.log(v[i_r])
    val = math.exp(max(min(lv, 700.0), -700.0))
    sd = np.minimum(sd, 25.0)
    sd_c = min(sd_c, 25.0)
    eq = dict(corr_rho2_h2=c, middle_layer=kind, beta=float(beta),
              combination=float(val), combination_factor=float(math.exp(sd_c)),
              rho2_factor=float(math.exp(sd[i_r])),
              h2_factor=float(math.exp(sd[i_h])),
              S2=float(v[i_h] / v[i_r]), T2=float(v[i_h] * v[i_r]), layer=i_r + 1)
    strong = abs(c) >= 0.9 and math.exp(sd_c) < 0.7 * min(math.exp(sd[i_r]), math.exp(sd[i_h])) + 0.3
    if strong and 0.6 <= beta <= 1.6:
        eq["determined"] = "T2"
        what = (f"close to its transverse resistance T{S} = ρ{S}h{S} = "
                f"{v[i_h] * v[i_r]:.4g} Ω·m² (Sunde's T-equivalence)")
    elif strong and -1.6 <= beta <= -0.6:
        eq["determined"] = "S2"
        what = (f"close to its conductance S{S} = h{S}/ρ{S} = {v[i_h] / v[i_r]:.4g} S "
                f"(Sunde's S-equivalence)")
    elif strong:
        eq["determined"] = "combination"
        what = ""
    else:
        eq["determined"] = "both"
    def fx(sdv):
        f = math.exp(sdv)
        return f"within ×{f:.2f}" if f < 20 else "not at all"
    unresolved = math.exp(sd[i_r]) >= 20 or math.exp(sd[i_h]) >= 20
    eq["unresolved"] = bool(unresolved)
    if eq["determined"] == "both":
        if math.exp(sd[i_r]) < 3 and math.exp(sd[i_h]) < 3:
            eq["statement"] = (
                f"ρ{S} and h{S} are resolved separately (correlation {c:+.2f}; "
                f"ρ{S} within ×{math.exp(sd[i_r]):.2f}, h{S} within "
                f"×{math.exp(sd[i_h]):.2f}).")
        else:
            eq["statement"] = (
                f"Layer {i_r + 1} is poorly resolved: ρ{S} {fx(sd[i_r])} and h{S} "
                f"{fx(sd[i_h])} (correlation {c:+.2f}), with no single combination "
                f"of the two fixed much better. More readings at spacings "
                f"comparable with its depth would be needed to pin it down.")
    elif unresolved:
        eq["statement"] = (
            f"ρ{S} and h{S} are traded against each other (correlation "
            f"{c:+.2f}): the data fix h{S}·ρ{S}^{beta:.2f} within "
            f"×{math.exp(sd_c):.2f}{', ' + what if what else ''}, but ρ{S} "
            f"and h{S} individually are not resolved at all — a thin layer "
            f"and a thick one with the same h{S}·ρ{S}^{beta:.2f} fit the "
            f"readings equally well. The values shown are one member of "
            f"that family. An electrode that reaches into the middle "
            f"layer should be checked with a thin and with a thick "
            f"version of it.")
    else:
        eq["statement"] = (
            f"ρ{S} and h{S} are traded against each other (correlation "
            f"{c:+.2f}): the data fix h{S}·ρ{S}^{beta:.2f} within "
            f"×{math.exp(sd_c):.2f}{', ' + what if what else ''}, but ρ{S} only "
            f"{fx(sd[i_r])} and h{S} {fx(sd[i_h])}. "
            f"Other models along that line fit the readings almost as "
            f"well; the earthing results that depend on the middle "
            f"layer alone should be checked at both ends of the range.")
    return eq


def _uncertainty(res, p, f, n, n_layers, lo, hi):
    """Linearised covariance of the log parameters, s²(JᵀJ)⁻¹, its
    correlations, and the combination of the middle layer's ρ and h that
    the data actually determine (the equivalence of tutorial §2.8)."""
    m = len(p)
    dof = n - m
    if dof <= 0:
        return None
    r0 = res(p)
    J = np.empty((n, m))
    for j in range(m):
        dp = np.zeros(m)
        dp[j] = 1e-5
        J[:, j] = (res(p + dp) - res(p - dp)) / 2e-5
    s2 = max(f / dof, 1e-12)
    U, sv, Vt = np.linalg.svd(J, full_matrices=False)
    cut = sv.max() * 1e-9
    inv = np.where(sv > cut, 1.0 / np.maximum(sv, 1e-300) ** 2, 0.0)
    C = (Vt.T * inv) @ Vt * s2
    sd = np.sqrt(np.maximum(np.diag(C), 0.0))
    corr = C / np.outer(np.maximum(sd, 1e-300), np.maximum(sd, 1e-300))
    names = ([f"rho{i + 1}" for i in range(n_layers)]
             + [f"h{i + 1}" for i in range(n_layers - 1)])
    v = np.exp(p)
    par = {}
    for i, nm in enumerate(names):
        si = float(min(sd[i], 25.0))            # beyond ×10¹⁰: not resolved at all
        par[nm] = dict(value=float(v[i]), sd_log=float(sd[i]),
                       low_68=float(v[i] * math.exp(-si)),
                       high_68=float(v[i] * math.exp(si)),
                       factor=float(math.exp(si)),
                       resolved=bool(sd[i] < math.log(3.0)))
    out = dict(params=par, names=names, corr=corr.tolist(), dof=dof,
               s_rms_pct=math.sqrt(s2) * 100.0,
               singular_values=sv.tolist())
    if n_layers >= 3:
        eqs = [_equivalence(C, sd, corr, v, k, n_layers + k)
               for k in range(1, n_layers - 1)]
        out["equivalences"] = eqs
        eq = eqs[0]
        out["equivalence"] = eq
    return out


def select_three(spacings, rho_app, two: dict, array: str = "wenner",
                 mn=None) -> dict:
    """Fit three layers, seeded with an existing two-layer fit ``two``
    (keys rho1, rho2, h, rms_pct), and test whether the third layer is
    supported (F test of the two extra parameters at the 5 % level, and an
    RMS at least 20 % lower)."""
    n = len(spacings)
    if n < 6:
        return dict(three=None, chosen=2, F=None, p_value=None,
                    reason=(f"Only {n} readings: a three-layer fit (five "
                            f"parameters) needs at least six, and eight or "
                            f"more to be meaningful."))
    r1, r2, h = float(two["rho1"]), float(two["rho2"]), float(two["h"])
    S = [[r1, r2, r2, h, h], [r1, r2, r1, h, 3 * h], [r1, r1, r2, 0.5 * h, 0.5 * h],
         [r1, math.sqrt(r1 * r2), r2, 0.5 * h, h]] + _starts(spacings, rho_app, 3)
    three = invert_layers(spacings, rho_app, 3, array, mn, starts=S)
    ss2 = (float(two["rms_pct"]) / 100.0) ** 2 * n
    F, pv = _f_test_p(ss2, three["ss"], n)
    better = three["rms_pct"] < 0.8 * float(two["rms_pct"])
    chosen = 3 if (pv is not None and pv < 0.05 and better) else 2
    rms2 = float(two["rms_pct"])
    if chosen == 3:
        reason = (f"The third layer is supported by the readings: the RMS "
                  f"misfit falls from {rms2:.2f} % (two layers) to "
                  f"{three['rms_pct']:.2f} % (three), and the F test of the two "
                  f"extra parameters gives p = {pv:.2g} (below 0.05).")
    elif pv is None:
        reason = "The F test needs more readings than parameters."
    else:
        reason = (f"The third layer is not supported: RMS {rms2:.2f} % (two "
                  f"layers) against {three['rms_pct']:.2f} % (three), F-test "
                  f"p = {pv:.2g}. The two-layer model is the one the readings support.")
    return dict(three=three, chosen=chosen, F=F, p_value=pv, reason=reason,
                rms_two=rms2, rms_three=three["rms_pct"])


def _starts_four(three: dict, xs) -> list:
    """Starting points for a four-layer fit, built from a three-layer fit by
    splitting each of its layers in two (the new layer more resistive or
    more conductive) and by adding a layer below it."""
    r, h = list(three["rho"]), list(three["h"])
    d = [h[0], h[0] + h[1]]
    a_max = max(xs)
    S = []
    for f in (0.3, 3.0):
        # split layer 1
        S.append([r[0], r[0] * f, r[1], r[2], 0.5 * h[0], 0.5 * h[0], h[1]])
        # split layer 2
        S.append([r[0], r[1], r[1] * f, r[2], h[0], 0.5 * h[1], 0.5 * h[1]])
        S.append([r[0], r[1] * f, r[1], r[2], h[0], 0.3 * h[1], 0.7 * h[1]])
        # split layer 3 (new basement below)
        for t in (0.5 * d[1], d[1], 2.0 * d[1]):
            S.append([r[0], r[1], r[2], r[2] * f, h[0], h[1], min(t, 4 * a_max)])
    # the three-layer model itself with a thin extra layer at each interface
    S.append([r[0], r[1], r[1], r[2], h[0], 0.5 * h[1], 0.5 * h[1]])
    return S


def select_four(spacings, rho_app, three: dict, array: str = "wenner",
                mn=None) -> dict:
    """Fit four layers, seeded with a three-layer fit, and keep the fourth
    only if it passes the same test as the third (F test of the two extra
    parameters at the 5 % level, RMS at least 20 % lower)."""
    n = len(spacings)
    if n < 9:
        return dict(four=None, chosen=3, F=None, p_value=None,
                    reason=(f"Only {n} readings: a four-layer fit (seven "
                            f"parameters) needs at least nine."))
    S = _starts_four(three, spacings)
    four = invert_layers(spacings, rho_app, 4, array, mn, starts=S)
    ss3 = three["ss"]
    d2 = n - 7
    F = ((ss3 - four["ss"]) / 2.0) / (four["ss"] / d2) if four["ss"] > 0 else None
    pv = None if F is None else (1.0 if F <= 0 else (d2 / (d2 + 2.0 * F)) ** (d2 / 2.0))
    better = four["rms_pct"] < 0.8 * three["rms_pct"]
    chosen = 4 if (pv is not None and pv < 0.05 and better) else 3
    reason = (f"{'A fourth layer is supported' if chosen == 4 else 'A fourth layer is not supported'}: "
              f"RMS {three['rms_pct']:.2f} % with three layers against "
              f"{four['rms_pct']:.2f} % with four, F-test p = {pv:.2g}.")
    return dict(four=four, chosen=chosen, F=F, p_value=pv, reason=reason,
                rms_three=three["rms_pct"], rms_four=four["rms_pct"])


def equivalent_simple(earth: LayeredEarth, depth: float, method: str = "auto") -> dict:
    """Equivalent uniform resistivity without a grid area: 'top' (ρ₁) or the
    depth-weighted average over the electrode penetration (small electrodes
    only).  The grid-size rule needs the area (``equivalent_uniform``)."""
    if method == "top" or not earth.h or depth <= earth.h[0]:
        return dict(rho_equivalent=earth.rho[0], method_used="top", penetration=depth,
                    note=("Electrodes stay in the top layer; ρ₁ used. For a grid "
                          "this can be badly wrong — give the grid area so that "
                          "the grid-size rule can be used."))
    bounds = [0.0] + list(earth.depths) + [math.inf]
    acc = 0.0
    parts = []
    for i, r in enumerate(earth.rho):
        a, b = bounds[i], min(bounds[i + 1], depth)
        if b > a:
            acc += r * (b - a)
            parts.append(f"{b - a:.2f} m in layer {i + 1}")
    return dict(rho_equivalent=acc / depth, method_used="weighted", penetration=depth,
                note=("Depth-weighted average over the electrode penetration ("
                      + ", ".join(parts) + "). This suits small electrodes only — "
                      "for a grid, give its area so the grid-size rule can be "
                      "used, or run the numerical solver."))


def compare_two_three(spacings, rho_app, array: str = "wenner", mn=None) -> dict:
    """Fit two and three layers and decide, by the F test and by the size
    of the improvement, whether the third layer is supported by the data."""
    n = len(spacings)
    two = invert_layers(spacings, rho_app, 2, array, mn)
    if n < 6:
        return dict(two=two, three=None, chosen=2, F=None, p_value=None,
                    reason=(f"Only {n} readings: a three-layer fit (five "
                            f"parameters) needs at least six, and eight or more "
                            f"to be meaningful."))
    # seed the three-layer search with the two-layer answer as well
    S = _starts(spacings, rho_app, 3)
    r1, r2 = two["rho"]
    h = two["h"][0]
    S = [[r1, r2, r2, h, h], [r1, r2, r1, h, 3 * h], [r1, r1, r2, 0.5 * h, 0.5 * h]] + S
    three = invert_layers(spacings, rho_app, 3, array, mn, starts=S)
    F, pv = _f_test_p(two["ss"], three["ss"], n)
    better = three["rms_pct"] < 0.8 * two["rms_pct"]
    chosen = 3 if (pv is not None and pv < 0.05 and better) else 2
    if chosen == 3:
        reason = (f"The third layer is supported by the data: the RMS misfit "
                  f"falls from {two['rms_pct']:.2f} % to {three['rms_pct']:.2f} % "
                  f"and the F test of the two extra parameters gives "
                  f"p = {pv:.2g} (< 0.05).")
    elif pv is None:
        reason = "The F test needs more readings than parameters."
    else:
        reason = (f"The third layer is not supported: RMS {two['rms_pct']:.2f} % "
                  f"(two layers) against {three['rms_pct']:.2f} % (three), "
                  f"F-test p = {pv:.2g}. The two-layer model is the one the readings support.")
    return dict(two=two, three=three, chosen=chosen, F=F, p_value=pv,
                reason=reason)


# ---------------------------------------------------------------------------
# Spectral solution: the exact kernel families for the deep images
# ---------------------------------------------------------------------------

def spectral_families(earth: LayeredEarth, src_layer: int, fld_layer: int,
                      lam, Z: float):
    """The four image families of the Green's function, summed exactly in
    the spectral domain.

    In the field layer the potential of the source, less its primary term,
    is the sum of up-going waves (sources below, e^{+λz}) and down-going
    waves (sources above, e^{−λz}), each with an s = ±1 dependence on z'.
    With w = z − z' (s = +1, centre w₀ = 0) or w = z + z' (s = −1, centre
    w₀ = Z), every family is  e^{±λ(w − w₀)} Φ(λ)  with

        Φ_{s,up}(λ)   = Σ_images amp·e^{−λ(shift − w₀)}
        Φ_{s,down}(λ) = Σ_images amp·e^{−λ(w₀ − shift)}.

    Φ is obtained by solving the boundary-value problem at each λ — φ in
    layer L is a_L e^{λ(z − b_L)} + b_L e^{−λ(z − t_L)} (t, b its top and
    bottom, so that no exponential grows inside the layer), with no current
    through the surface, φ and (1/ρ)∂φ/∂z continuous at each interface and
    a = 0 in the last layer — once for the primary's value at the top of
    the source layer and once for its value at the bottom.

    Returns {(s, 'up'|'down'): Φ(λ)}.
    """
    lam = np.asarray(lam, float)
    N = earth.N
    rho = np.asarray(earth.rho, float)
    d = np.array([0.0] + list(earth.depths), float)
    top = d[:N]
    bot = np.array([d[L + 1] if L < N - 1 else d[L] for L in range(N)])
    S, F = src_layer - 1, fld_layer - 1
    n = 2 * N
    nl = lam.size
    M = np.zeros((nl, n, n))

    def ea(L, z):
        return np.zeros(nl) if L == N - 1 else np.exp(lam * (z - bot[L]))

    def eb(L, z):
        return np.exp(-lam * (z - top[L]))

    # surface: ∂φ/∂z = 0 (divided by λ)
    M[:, 0, 0] = ea(0, 0.0)
    M[:, 0, 1] = -eb(0, 0.0)
    row = 1
    for k in range(1, N):
        zc, u, w_ = d[k], k - 1, k
        M[:, row, 2 * u] = ea(u, zc); M[:, row, 2 * u + 1] = eb(u, zc)
        M[:, row, 2 * w_] = -ea(w_, zc); M[:, row, 2 * w_ + 1] = -eb(w_, zc)
        row += 1
        M[:, row, 2 * u] = ea(u, zc) / rho[u]; M[:, row, 2 * u + 1] = -eb(u, zc) / rho[u]
        M[:, row, 2 * w_] = -ea(w_, zc) / rho[w_]; M[:, row, 2 * w_ + 1] = eb(w_, zc) / rho[w_]
        row += 1
    M[:, row, 2 * (N - 1)] = 1.0
    # right-hand sides.  Primary p = e^{−λ|z − z'|} inside layer S only.
    # (i) unit value at the top plane of S (p = 1, ∂p/∂z /λ = +1),
    # (ii) unit value at the bottom plane of S (p = 1, ∂p/∂z /λ = −1).
    rhs = np.zeros((nl, n, 2))
    # top of S
    if S == 0:
        rhs[:, 0, 0] = -1.0                  # a − b + (+1) = 0
    else:
        r0 = 1 + 2 * (S - 1)                  # rows for plane S
        rhs[:, r0, 0] = +1.0                  # φ_u − φ_S(hom) = p
        rhs[:, r0 + 1, 0] = +1.0 / rho[S]     # flux: (+1)/ρ_S
    if S < N - 1:
        r0 = 1 + 2 * S                        # rows for plane S+1
        rhs[:, r0, 1] = -1.0                  # φ_S(hom) + p − φ_dn = 0
        rhs[:, r0 + 1, 1] = +1.0 / rho[S]     # −(−1)/ρ_S
    sol = np.linalg.solve(M, rhs)            # (nl, n, 2)
    aU, bU = sol[:, 2 * F, 0], sol[:, 2 * F + 1, 0]   # × e^{−λ(z' − t_S)}
    aD, bD = sol[:, 2 * F, 1], sol[:, 2 * F + 1, 1]   # × e^{−λ(b_S − z')}
    tS, bS, tF, bF = top[S], bot[S], top[F], bot[F]
    out = {}
    # P_up·a·e^{λ(z−b_F)} = e^{λ(z−z')}·a·e^{−λ(b_F − t_S)}
    out[(1, "up")] = aU * np.exp(-lam * (bF - tS)) if F < N - 1 else np.zeros(nl)
    # P_dn·a·e^{λ(z−b_F)} = e^{λ(z+z')}·a·e^{−λ(b_S + b_F)};  Φ = ·e^{λZ}
    out[(-1, "up")] = (aD * np.exp(-lam * (bS + bF - Z))
                       if (F < N - 1 and S < N - 1) else np.zeros(nl))
    # P_up·b·e^{−λ(z−t_F)} = e^{−λ(z+z')}·b·e^{λ(t_S + t_F)};  Φ = ·e^{−λZ}
    out[(-1, "down")] = bU * np.exp(lam * (tS + tF - Z))
    # P_dn·b·e^{−λ(z−t_F)} = e^{−λ(z−z')}·b·e^{−λ(b_S − t_F)}
    out[(1, "down")] = (bD * np.exp(-lam * (bS - tF)) if S < N - 1
                        else np.zeros(nl))
    return out


# ---------------------------------------------------------------------------
# Compressed Green's function for the boundary-element solver
# ---------------------------------------------------------------------------

class LayeredGreen:
    """The layered-earth Green's function in the form the solver evaluates
    millions of times.

    For a source at depth z' and a field point at depth z (both no deeper
    than Z), an image term is  amp / √(r² + (w − shift)²)  with w = z − z'
    (s = +1, |w| ≤ Z, centre w₀ = 0) or w = z + z' (s = −1, 0 ≤ w ≤ 2Z,
    w₀ = Z).  With δ = |shift − w₀| the distance of an image from that
    range's centre:

    * δ ≤ 3Z        exact images, one by one;
    * 3Z < δ ≤ 12Z  images merged in bins 2 % wide in δ (amplitude signs and
                    sides apart), each at the amplitude-weighted mean
                    position — an error of second order in the bin width;
    * δ > 12Z       six tables of r holding the Taylor coefficients about
                    w₀, up to (w − w₀)⁵, of the sum of ALL the remaining
                    images, computed from the exact spectral families
                    (``spectral_families``) less the explicit images and
                    Hankel-transformed; the first neglected term is below
                    (1/11)⁶ ≈ 6·10⁻⁷ of that part.

    The image tracing therefore stops at δ ≈ 15Z instead of following
    slowly decaying waves for thousands of bounces.
    """

    NEAR, MID, BIN, ORDER, FULL = 3.0, 8.0, 0.05, 7, 5.0

    def __init__(self, earth: LayeredEarth, Z: float, r_max: float,
                 tol: float = 1e-10):
        self.earth = earth
        self.tol = tol
        self.Z = max(float(Z), 0.05)
        self.r_max = max(float(r_max), 10.0 * self.Z)
        self._build()

    def _layers(self):
        """Layers that can hold a source or field point (top < Z)."""
        tops = [0.0] + list(self.earth.depths)
        return [L + 1 for L in range(self.earth.N) if tops[L] < self.Z + 1e-12]

    def _rgrid(self):
        Z = self.Z
        lin = np.arange(0.0, 3.0 * Z + 1e-12, Z / 4.0)
        hi = 1.5 * self.r_max + 3.0 * Z
        geo = np.geomspace(3.0 * Z, hi, max(2, int(math.log(hi / (3 * Z)) / 0.01) + 1))
        return np.unique(np.concatenate([lin, geo]))

    def _build(self):
        Z = self.Z
        self.rg = self._rgrid()
        self.terms, self.tables, self.full = {}, {}, {}
        self.r_full = float(self.rg[self.rg >= self.FULL * Z][0])
        cut = (self.MID + 3.0) * Z
        nexact = nbinned = 0
        lay = self._layers()
        # Hankel nodes for the far tables: the remainder decays like
        # e^{−λ·11Z}; geometric panels near 0 (deep images), then π/r_max.
        lam_max = 40.0 / ((self.MID - 1.0) * Z)
        rmax = float(self.rg.max())
        geo = np.geomspace(1e-9 / Z, min(0.5 / rmax, lam_max), 60)
        step = min(math.pi / rmax, 0.25 / Z)
        lin = np.linspace(geo[-1], lam_max, max(2, int(math.ceil((lam_max - geo[-1]) / step)) + 1))
        edges = np.concatenate([[0.0], geo, lin[1:]])
        t, w = _GL10
        a_, b_ = edges[:-1], edges[1:]
        lam = ((0.5 * (a_ + b_))[:, None] + (0.5 * (b_ - a_))[:, None] * t[None, :]).ravel()
        wts = ((0.5 * (b_ - a_))[:, None] * w[None, :]).ravel()
        J = j0(self.rg[:, None] * lam[None, :]) * wts[None, :]
        lam = np.maximum(lam, 1e-300)
        for sl in lay:
            ser = image_series(self.earth, sl, tol=self.tol, prune_beyond=cut,
                               with_direction=True)
            for fl in lay:
                s, sh, a, dr = ser[fl]
                fam = spectral_families(self.earth, sl, fl, lam, Z)
                ex_s, ex_sh, ex_a = [], [], []
                T = {}
                for sg in (1, -1):
                    w0 = 0.0 if sg == 1 else Z
                    Ttab = np.zeros((self.ORDER + 1, len(self.rg)))
                    for dname, dcode, sig in (("up", 0, 1.0), ("down", 1, -1.0)):
                        m = (s == sg) & (dr == dcode)
                        shs, as_ = sh[m], a[m]
                        dl = np.abs(shs - w0)
                        near = dl <= self.NEAR * Z
                        mid = (dl > self.NEAR * Z) & (dl <= self.MID * Z)
                        ex_s.append(np.full(near.sum(), sg)); ex_sh.append(shs[near])
                        ex_a.append(as_[near]); nexact += int(near.sum())
                        if mid.any():
                            bs, ba = self._bin(shs[mid], as_[mid], w0, self.BIN)
                            ex_s.append(np.full(len(bs), sg)); ex_sh.append(bs)
                            ex_a.append(ba); nbinned += len(bs)
                        # far remainder of this family in the spectral domain
                        expl = near | mid
                        dist = sig * (shs[expl] - w0)       # e^{−λ·dist}
                        Phi = fam[(sg, dname)].copy()
                        for i in range(0, expl.sum(), 512):
                            Phi -= (as_[expl][i:i + 512][None, :] *
                                    np.exp(-lam[:, None] * dist[i:i + 512][None, :])).sum(1)
                        for k in range(self.ORDER + 1):
                            Ttab[k] += J @ (((sig * lam) ** k) * Phi) / math.factorial(k)
                    T[sg] = (w0, Ttab)
                # the primary is an explicit exact image (s = +1, shift 0, dir 2)
                m = dr == 2
                if m.any():
                    ex_s.append(s[m]); ex_sh.append(sh[m]); ex_a.append(a[m]); nexact += 1
                self.terms[(sl, fl)] = (np.concatenate(ex_s).astype(int),
                                        np.concatenate(ex_sh), np.concatenate(ex_a))
                self.tables[(sl, fl)] = T
                # complete tables (explicit images added in closed form) for
                # points at least FULL·Z apart horizontally
                full = {}
                es, esh, ea_ = self.terms[(sl, fl)]
                for sg, (w0, Ttab) in T.items():
                    Tf = Ttab.copy()
                    m = es == sg
                    sel = self.rg >= self.r_full
                    Tf[:, ~sel] = np.nan
                    if m.any():
                        Tf[:, sel] += self._taylor_images(self.rg[sel], esh[m], ea_[m], w0)
                    full[sg] = (w0, Tf)
                self.full[(sl, fl)] = full
        self.counts = dict(exact=nexact, binned=nbinned)

    def _taylor_images(self, r, sh, a, w0):
        """Taylor coefficients about w0 of Σ a/√(r² + (w − sh)²):
        the k-th is (−1)^k P_k(u/R)/R^{k+1}, u = w0 − sh, R = √(r² + u²)
        (the axial multipole expansion of 1/R)."""
        out = np.zeros((self.ORDER + 1, len(r)))
        for i in range(0, len(sh), 2048):
            u = (w0 - sh[i:i + 2048])[None, :]
            aa = a[i:i + 2048][None, :]
            R = np.sqrt(r[:, None] ** 2 + u * u)
            x = u / R
            P0, P1 = np.ones_like(x), x
            invR = 1.0 / R
            powR = invR.copy()
            out[0] += (aa * P0 * powR).sum(1)
            powR = powR * invR
            out[1] += -(aa * P1 * powR).sum(1)
            Pm, Pk = P0, P1
            for k in range(2, self.ORDER + 1):
                Pn = ((2 * k - 1) * x * Pk - (k - 1) * Pm) / k
                powR = powR * invR
                out[k] += ((-1) ** k) * (aa * Pn * powR).sum(1)
                Pm, Pk = Pk, Pn
        return out

    @staticmethod
    def _bin(sh, a, w0, rel):
        """Merge images in bins of relative width ``rel`` in |shift − w0|,
        each side of w0 and each sign of amplitude apart, at the
        amplitude-weighted mean position."""
        side = np.sign(sh - w0)
        dl = np.abs(sh - w0)
        k = np.floor(np.log(dl) / math.log1p(rel)).astype(np.int64)
        code = (k * 2 + (side > 0)) * 2 + (a > 0)
        u, inv = np.unique(code, return_inverse=True)
        A = np.bincount(inv, weights=a, minlength=len(u))
        Mm = np.bincount(inv, weights=a * sh, minlength=len(u))
        return Mm / A, A

    # -- evaluation -----------------------------------------------------------
    def ensure(self, Z: float, r_max: float):
        """Rebuild if a point is deeper, or further away, than planned."""
        if Z > self.Z * (1 + 1e-9) or r_max > self.r_max * (1 + 1e-9):
            self.Z = max(self.Z, float(Z))
            self.r_max = max(self.r_max, float(r_max) * 1.5)
            self._build()

    def sum_terms(self, sl: int, fl: int, rh2, zf, zs, skip_direct=False):
        """Σ amp/R over all images, without the ρ_src/4π factor.
        rh2: (M, Q) squared horizontal distances; zf: (M, 1); zs: (1, Q).

        Pairs at least FULL·Z apart horizontally are taken from the complete
        Taylor tables (every image lies at least that far from the field
        point, so the series in w − w₀ converges with ratio ≤ 1/FULL; the
        first neglected term, of order 8, is below 5⁻⁸ ≈ 3·10⁻⁶); nearer
        pairs from the explicit images plus the deep-image tables."""
        shape = np.broadcast(rh2, zf, zs).shape
        rh2 = np.broadcast_to(rh2, shape)
        zf = np.broadcast_to(zf, shape)
        zs = np.broadcast_to(zs, shape)
        far = (rh2 >= self.r_full ** 2) & (not skip_direct)
        if far.any():
            acc = np.zeros(shape)
            rhf = np.sqrt(rh2[far])
            for sg, (w0, Tf) in self.full[(sl, fl)].items():
                dw = (zf[far] - sg * zs[far]) - w0
                poly = np.interp(rhf, self.rg, Tf[-1])
                for k in range(len(Tf) - 2, -1, -1):
                    poly = np.interp(rhf, self.rg, Tf[k]) + dw * poly
                acc[far] += poly
            near = ~far
            if near.any():
                acc[near] = self._sum_near(sl, fl, rh2[near], zf[near], zs[near], skip_direct)
            return acc
        return self._sum_near(sl, fl, rh2, zf, zs, skip_direct)

    def _sum_near(self, sl, fl, rh2, zf, zs, skip_direct):
        s, sh, a = self.terms[(sl, fl)]
        acc = np.zeros(np.broadcast(rh2, zf, zs).shape)
        for sg in (1, -1):
            m = s == sg
            w = zf - sg * zs
            for shk, ak in zip(sh[m], a[m]):
                if skip_direct and sg == 1 and shk == 0.0 and sl == fl and ak == 1.0:
                    continue
                acc += ak / np.sqrt(np.maximum(rh2 + (w - shk) ** 2, 1e-24))
        rh = np.sqrt(rh2)
        for sg, (w0, T) in self.tables[(sl, fl)].items():
            dw = (zf - sg * zs) - w0
            poly = np.interp(rh, self.rg, T[-1])
            for k in range(len(T) - 2, -1, -1):
                poly = np.interp(rh, self.rg, T[k]) + dw * poly
            acc += poly
        return acc
